export async function copySiteUrl(url, clipboard = globalThis.navigator?.clipboard) {
 if (!sites.some(site=>site.url===url)) throw new Error('Unknown site URL');
 try {
  if (typeof clipboard?.writeText !== 'function') return false;
  await clipboard.writeText(url);
  return true;
 } catch { return false; }
}
